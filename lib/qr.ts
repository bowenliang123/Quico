import QRCode from 'qrcode';

/** 默认二维码边长 (px) */
const DEFAULT_QR_SIDE = 250;

/**
 * 生成二维码 Data URL
 * @param text 二维码内容
 * @param side 边长 (px)
 */
export async function renderQrDataUrl(text: string, side: number = DEFAULT_QR_SIDE): Promise<string> {
  if (!text) {
    return '';
  }
  return QRCode.toDataURL(text, {
    errorCorrectionLevel: 'L',
    margin: 1,
    width: side,
    color: { dark: '#000000', light: '#ffffff' },
  });
}

/**
 * 下载带网址和插件水印的二维码 PNG 文件
 * @param text 二维码内容 (渲染在右侧 + 作为文件名)
 * @param qrDataUrl 二维码 Data URL
 */
export async function downloadDecoratedQrPng(text: string, qrDataUrl: string): Promise<void> {
  if (!qrDataUrl) {
    return;
  }
  const qrImage = await loadImage(qrDataUrl);

  // 画布尺寸沿用旧版设计
  const canvasWidth = 700;
  const canvasHeight = 300;
  const qrPadding = 7;
  const qrMargin = 25;
  const qrLength = 250;
  const textX = qrLength + qrMargin * 2;
  const textMaxWidth = 380;

  const canvas = document.createElement('canvas');
  canvas.width = canvasWidth;
  canvas.height = canvasHeight;
  const ctx = canvas.getContext('2d');
  if (!ctx) {
    return;
  }

  // 白色背景
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, canvasWidth, canvasHeight);

  // 二维码外框
  ctx.strokeStyle = '#a8a8a8';
  ctx.lineWidth = 1;
  ctx.strokeRect(
    qrMargin - qrPadding,
    qrMargin - qrPadding,
    qrLength + qrPadding * 2,
    qrLength + qrPadding * 2,
  );

  // 二维码
  ctx.drawImage(qrImage, qrMargin, qrMargin);

  // 插件水印
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, '0');
  const watermark = `Generated by Quico Chrome Extension. ${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}`;
  ctx.fillStyle = '#a8a8a8';
  ctx.font = '10px Menlo, Monaco, Consolas, Courier, monospace';
  ctx.fillText(watermark, canvasWidth - textMaxWidth - 16, canvasHeight - 20, textMaxWidth);

  // 网址文本, 每行 40 字符折行渲染
  ctx.fillStyle = '#3333ff';
  ctx.font = '16px Menlo, Monaco, Consolas, Courier, monospace';
  let textY = qrMargin + 6;
  for (let i = 0; i < text.length; i += 40) {
    ctx.fillText(text.slice(i, i + 40), textX, textY, textMaxWidth);
    textY += 25;
  }

  // 触发下载
  const link = document.createElement('a');
  link.href = canvas.toDataURL().replace(/^data:image\/[^;]/, 'data:application/octet-stream');
  link.download = buildQrFilename(text);
  document.body.appendChild(link);
  link.click();
  link.remove();
}

/** 由二维码内容生成下载文件名, 过滤文件系统非法字符并限制长度 */
function buildQrFilename(text: string): string {
  const sanitized = text.replace(/[\\/:*?"<>|\s]+/g, '_').slice(0, 60);
  return `Quico二维码 ${sanitized || 'qr'}.png`;
}

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error('二维码图片加载失败'));
    image.src = src;
  });
}
